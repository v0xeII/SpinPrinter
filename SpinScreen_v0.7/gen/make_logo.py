"""Turn the "S" of the SpinSlicer icon (assets/spinslicer.svg in the SpinSlicer repo) into an
anti-aliased 8-bit alpha mask for SpinScreen. Pure Python, no libraries.
usage: make_logo.py <spinslicer.svg> <out logo.h> [preview.png]
The tile, the vial and the arrow are plain shapes and are drawn in ui.cpp from the same
SVG numbers; only the letter needs a bitmap."""
import re, struct, sys, zlib

SVG, OUT = sys.argv[1], sys.argv[2]
PREVIEW = sys.argv[3] if len(sys.argv) > 3 else None
SCALE = 0.5   # mask pixels per SVG unit (the tile is 256 units): sharp down to ~40 px tiles, 2.5 KB
SS = 4        # supersampling per axis

svg = open(SVG, encoding="utf-8").read()
d = re.search(r'<path d="(M[^"]+Z)" fill="#FF8DB5"', svg).group(1)


def flatten(d, steps=10):
    """M/H/Q/Z path -> list of polygons (lists of points)."""
    toks = re.findall(r"[MHQLZ]|-?\d+(?:\.\d+)?", d)
    polys, cur, x, y, i = [], [], 0.0, 0.0, 0
    while i < len(toks):
        t = toks[i]; i += 1
        if t == "M":
            if cur: polys.append(cur)
            x, y = float(toks[i]), float(toks[i + 1]); i += 2; cur = [(x, y)]
        elif t == "L":
            x, y = float(toks[i]), float(toks[i + 1]); i += 2; cur.append((x, y))
        elif t == "H":
            x = float(toks[i]); i += 1; cur.append((x, y))
        elif t == "Q":
            cx, cy, ex, ey = (float(v) for v in toks[i:i + 4]); i += 4
            for s in range(1, steps + 1):
                u = s / steps
                cur.append(((1 - u) ** 2 * x + 2 * (1 - u) * u * cx + u * u * ex,
                            (1 - u) ** 2 * y + 2 * (1 - u) * u * cy + u * u * ey))
            x, y = ex, ey
        elif t == "Z":
            if cur: polys.append(cur); cur = []
        else:
            raise SystemExit("unexpected path token " + t)
    if cur: polys.append(cur)
    return polys


polys = flatten(d)
edges = [(p[k], p[(k + 1) % len(p)]) for p in polys for k in range(len(p))]
xs = [x for p in polys for x, _ in p]; ys = [y for p in polys for _, y in p]
X0, Y0 = int(min(xs)) - 2, int(min(ys)) - 2           # SVG units, a small margin
W = int((max(xs) + 2 - X0) * SCALE) + 1
H = int((max(ys) + 2 - Y0) * SCALE) + 1


def coverage(edges, W, H, x0, y0, scale):
    """nonzero-winding scanline fill with SSxSS samples per pixel -> 0..255 per pixel"""
    acc = [0] * (W * H)
    for sy in range(H * SS):
        py = y0 + (sy + 0.5) / SS / scale
        xs = []
        for (ax, ay), (bx, by) in edges:
            if (ay <= py) != (by <= py):
                xs.append((ax + (py - ay) * (bx - ax) / (by - ay), 1 if by > ay else -1))
        xs.sort()
        wind, row = 0, (sy // SS) * W
        for k in range(len(xs) - 1):
            wind += xs[k][1]
            if wind == 0: continue
            # samples whose centre lies in [xa, xb)
            a = (xs[k][0] - x0) * scale * SS - 0.5
            b = (xs[k + 1][0] - x0) * scale * SS - 0.5
            for sx in range(max(0, int(a) + (a > int(a))), min(W * SS, int(b) + (b > int(b)))):
                acc[row + sx // SS] += 1
    return [min(255, v * 255 // (SS * SS)) for v in acc]


mask = coverage(edges, W, H, X0, Y0, SCALE)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by gen/make_logo.py from assets/spinslicer.svg (SpinSlicer). Do not edit.\n")
    f.write("// Alpha mask of the \"S\" in the SpinSlicer icon; SVG units: x = LOGO_S_X0 + px / LOGO_S_SCALE.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write(f"static const int LOGO_S_W = {W}, LOGO_S_H = {H};\n")
    f.write(f"static const float LOGO_S_X0 = {X0}.f, LOGO_S_Y0 = {Y0}.f, LOGO_S_SCALE = {SCALE}f;\n")
    f.write(f"static const uint8_t LOGO_S[{W * H}] = {{\n")
    for r in range(H):
        f.write("  " + ",".join(str(v) for v in mask[r * W:(r + 1) * W]) + ",\n")
    f.write("};\n")
print(f"{OUT}: {W}x{H} mask, {W * H} bytes")

if PREVIEW:  # the whole icon at 256 px, the reference to compare the firmware against
    N = 256
    pix = bytearray(N * N * 3)
    def put(x, y, c, a):
        o = (y * N + x) * 3
        for j in range(3): pix[o + j] = int(pix[o + j] * (1 - a) + c[j] * a)
    import math
    PINK, INK = (0xFF, 0x8D, 0xB5), (0x14, 0x12, 0x17)
    def inside_rr(x, y):
        qx, qy = max(abs(x - 128) - 72, 0), max(abs(y - 128) - 72, 0)
        return math.hypot(qx, qy) <= 56
    def seg_d(px, py, a, b):
        vx, vy = b[0] - a[0], b[1] - a[1]
        if vx == 0 and vy == 0: return math.hypot(px - a[0], py - a[1])
        t = max(0, min(1, ((px - a[0]) * vx + (py - a[1]) * vy) / (vx * vx + vy * vy)))
        return math.hypot(px - a[0] - t * vx, py - a[1] - t * vy)
    tri = [(234.7, 116.8), (241.6, 97.6), (219.2, 103.6)]
    def in_tri(px, py):
        s = [((b[0] - a[0]) * (py - a[1]) - (b[1] - a[1]) * (px - a[0])) for a, b in zip(tri, tri[1:] + tri[:1])]
        return all(v >= 0 for v in s) or all(v <= 0 for v in s)
    scov = coverage(edges, N, N, 0, 0, 1.0)
    for y in range(N):
        for x in range(N):
            cnt = [0, 0, 0]
            for sy in range(2):
                for sx in range(2):
                    px, py = x + (sx + .5) / 2, y + (sy + .5) / 2
                    if not inside_rr(px, py): continue
                    r = math.hypot(px - 128, py - 128)
                    ang = math.atan2(py - 128, px - 128)
                    on_arc = abs(r - 106) <= 4 and -1.745 <= ang <= -0.262
                    on_arc = on_arc or seg_d(px, py, (109.6, 23.6), (109.6, 23.6)) <= 4 or seg_d(px, py, (230.4, 100.6), (230.4, 100.6)) <= 4
                    on_tri = in_tri(px, py) or min(seg_d(px, py, a, b) for a, b in zip(tri, tri[1:] + tri[:1])) <= 2
                    cnt[1 if (r <= 88 or on_arc or on_tri) else 0] += 1
            a_tile = (cnt[0] + cnt[1]) / 4
            if a_tile: put(x, y, PINK, a_tile)
            if cnt[1]: put(x, y, INK, cnt[1] / max(1, cnt[0] + cnt[1]))
            if scov[y * N + x]: put(x, y, PINK, scov[y * N + x] / 255)
    ch = lambda t, dd: struct.pack(">I", len(dd)) + t + dd + struct.pack(">I", zlib.crc32(t + dd))
    raw = b"".join(b"\0" + bytes(pix[r * N * 3:(r + 1) * N * 3]) for r in range(N))
    open(PREVIEW, "wb").write(b"\x89PNG\r\n\x1a\n" + ch(b"IHDR", struct.pack(">IIBBBBB", N, N, 8, 2, 0, 0, 0)) + ch(b"IDAT", zlib.compress(raw)) + ch(b"IEND", b""))
    print("preview", PREVIEW)
