"""Generate anti-aliased 4-bit bitmap fonts (Latin + Cyrillic) for SpinScreen.
usage: make_fonts.py <Onest[wght].ttf> <out fonts.h>"""
import sys

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

TTF, OUT = sys.argv[1], sys.argv[2]
# glyphs Onest does not have (∞) come from DejaVu Sans Bold (free licence)
FALLBACK = sys.argv[3] if len(sys.argv) > 3 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
HAVE = set(TTFont(TTF).getBestCmap())

BASIC = list(range(32, 127)) + [0x401, 0x451] + list(range(0x410, 0x450)) + \
    [0xB0, 0xAB, 0xBB, 0x2014, 0x2026, 0xB7, 0x2192, 0x2190, 0x2191, 0x2193, 0x2022, 0x2713, 0xD7, 0xB1, 0x221E]
DIGITS = [ord(c) for c in " 0123456789.,:%/-+"] + [0x221E]

# name, px size, weight, charset
FONTS = [("F_SM", 13, 500, BASIC), ("F_MD", 17, 600, BASIC),
         ("F_LG", 24, 750, BASIC), ("F_XL", 44, 800, DIGITS)]


def render(size, weight, cps):
    main = ImageFont.truetype(TTF, size)
    main.set_variation_by_axes([weight])
    fb = ImageFont.truetype(FALLBACK, size)
    asc, desc = main.getmetrics()
    glyphs, data = [], bytearray()
    for cp in sorted(set(cps)):
        ch = chr(cp)
        f = main if cp in HAVE else fb
        adv = round(f.getlength(ch))
        W, H = size * 3, size * 3
        im = Image.new("L", (W, H), 0)
        ox, oy = size, size + asc
        ImageDraw.Draw(im).text((ox, oy), ch, font=f, fill=255, anchor="ls")
        bb = im.getbbox()
        if bb is None:
            glyphs.append((cp, len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        px = im.crop(bb).load()
        off = len(data)
        for y in range(h):
            row = [min(15, (px[x, y] + 8) // 17) for x in range(w)]
            if w % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append((row[i] << 4) | row[i + 1])
        # xo: from pen x to bitmap left; yo: from baseline to bitmap top (negative = above)
        glyphs.append((cp, off, w, h, x0 - ox, y0 - oy, adv))
    return glyphs, data, asc, desc


out = ["// Generated by gen/make_fonts.py from Onest (SIL Open Font License); ∞ from DejaVu Sans. Do not edit.",
       "#pragma once", '#include "gfx.h"', ""]
for name, size, weight, cps in FONTS:
    g, d, asc, desc = render(size, weight, cps)
    out.append(f"static const uint8_t {name}_bmp[{len(d)}] = {{")
    for i in range(0, len(d), 24):
        out.append("  " + ",".join(f"0x{b:02x}" for b in d[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}_gl[{len(g)}] = {{")
    for cp, off, w, h, xo, yo, adv in g:
        out.append(f"  {{0x{cp:04x},{off},{w},{h},{xo},{yo},{adv}}},")
    out.append("};")
    out.append(f"static const Font {name} = {{{name}_bmp, {name}_gl, {len(g)}, {asc + desc}, {asc}}};")
    out.append("")
    print(name, size, "glyphs", len(g), "bytes", len(d))
open(OUT, "w").write("\n".join(out))
